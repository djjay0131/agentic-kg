class TestRouterMaps:
    """Every router return must be a key of that edge's path map.

    The #164 staging failure was a map keyed ``"select_problem"`` for a router
    that returns ``"continue"``: LangGraph raised ``KeyError: 'continue'`` only
    on the first live success-path run. Validating the declared ``Literal``
    return against the map at build time makes that a CI failure instead.
    """

    def test_every_declared_return_is_a_key_of_its_edge_map(self):
        edges = workflow_edges()
        assert {source for source, _, _ in edges} == {
            "ranking",
            "select_problem",
            "continuation",
            "approve_proposal",
            "evaluation",
            "review_evaluation",
        }
        for source, router, targets in edges:
            declared = set(get_args(get_type_hints(router)["return"]))
            assert declared, f"{source} router has no Literal return"
            assert declared == set(targets), (
                f"{source} edge maps {sorted(targets)} but its router returns "
                f"{sorted(declared)}"
            )

    def test_checked_path_map_rejects_a_missing_route(self):
        """The exact #164 regression: a router return with no map entry."""
        with pytest.raises(ValueError, match="continue"):
            _checked_path_map(
                _should_continue_after_agent, {"end": END}
            )

    def test_checked_path_map_rejects_an_extra_route(self):
        with pytest.raises(ValueError):
            _checked_path_map(
                _should_continue_after_agent,
                {"continue": "select_problem", "end": END, "bogus": END},
            )


