    async def test_ranking_success_reaches_the_select_gate(self, mock_agents):
        """Regression for #164: a successful ranking must route "continue"."""
        from langgraph.checkpoint.memory import MemorySaver

        ranking, continuation, evaluation, synthesis = mock_agents
        ranking.run.return_value = {
            "status": "running",
            "current_step": "ranking",
            "ranked_problems": [
                {"problem_id": "p1", "statement": "Problem", "score": 0.9}
            ],
        }
        graph = build_workflow(*mock_agents, checkpointer=MemorySaver())
        state = create_initial_state()
        config = {"configurable": {"thread_id": state["run_id"]}}

        await graph.ainvoke(state, config=config)

        snapshot = await graph.aget_state(config)
        assert snapshot.next == ("select_problem",)
        continuation.run.assert_not_called()

